package testing

import uniffi.mediagram_core.SetSummary
import uniffi.mediagram_core.SubtitleTrack

/** A catalog row with every field a test does not name left at its plainest. */
fun setSummary(
    setId: String = "set-1",
    kind: String = "movie",
    title: String? = "Title",
    show: String? = null,
    chap: String? = null,
    path: String? = null,
    season: Int? = null,
    episodeFirst: Int? = null,
    episodeLast: Int? = null,
    year: Int? = null,
    container: String = "mp4",
    vcodec: String? = null,
    acodec: String? = null,
    quality: String? = null,
    hdr: String? = null,
    duration: Int? = null,
    posterKey: String? = null,
    posterPath: String? = null,
    total: Long = 0L,
    partCount: Int = 1,
    addedAt: Long = 0,
    fsk: String? = null,
    genres: List<String> = emptyList(),
    subtitles: List<SubtitleTrack> = emptyList(),
    alang: List<String> = emptyList(),
    slang: List<String> = emptyList(),
    hasSummary: Boolean = false,
    backdropPath: String? = null,
    seasonPosterPath: String? = null,
    tagline: String? = null,
    rating: Double? = null,
    popularity: Double? = null,
    showStatus: String? = null,
    collectionId: Long? = null,
    collectionName: String? = null,
    seriesType: String? = null,
    anime: Boolean = false,
    category: String? = null,
): SetSummary = SetSummary(
    setId = setId,
    kind = kind,
    title = title,
    show = show,
    chap = chap,
    path = path,
    season = season?.toUInt(),
    episodeFirst = episodeFirst?.toUInt(),
    episodeLast = episodeLast?.toUInt(),
    year = year?.toUInt(),
    container = container,
    vcodec = vcodec,
    acodec = acodec,
    quality = quality,
    hdr = hdr,
    duration = duration?.toUInt(),
    posterKey = posterKey,
    posterPath = posterPath,
    total = total.toULong(),
    partCount = partCount.toUInt(),
    addedAt = addedAt,
    fsk = fsk,
    genres = genres,
    subtitles = subtitles,
    alang = alang,
    slang = slang,
    hasSummary = hasSummary,
    backdropPath = backdropPath,
    seasonPosterPath = seasonPosterPath,
    tagline = tagline,
    rating = rating,
    popularity = popularity,
    showStatus = showStatus,
    collectionId = collectionId?.toULong(),
    collectionName = collectionName,
    seriesType = seriesType,
    anime = anime,
    category = category,
)
